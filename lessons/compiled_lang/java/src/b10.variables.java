class B10Variables {
    public static void main(String[] args) {
        int number = 5;
        char character = 'a';
        String text = "This is a string";

        System.out.printf("Number is %d.\n", number);
        System.out.printf("Character is '%c'.\n", character);
        System.out.printf("String is \"%s\".\n", text);
    }
}
