class B00Variables {
    public static void main(String[] args) {
        int number = 5;
        char character = 'a';
        String text = "This is a string";

        String output = "Number is " + number + ".\n"
                + "Character is '" + character + "'.\n"
                + "String is \"" + text + "\".\n";

        System.out.print(output);
    }
}
