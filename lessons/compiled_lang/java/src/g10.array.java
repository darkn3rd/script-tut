class G10Array {
    public static void main(String[] args) {
        String[] nicknames = {"bob", "ed", "steve", "ralph", "joe", "deb", "kate"};

        System.out.println("The names are: ");
        for (String name : nicknames) {
            System.out.println("  " + name);
        }
    }
}
