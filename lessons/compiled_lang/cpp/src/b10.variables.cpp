#include <iostream>
#include <string>

int main() {
    int number = 5;
    char character = 'a';
    std::string text = "This is a string";

    std::cout << "Number is " << number << ".\n";
    std::cout << "Character is '" << character << "'.\n";
    std::cout << "String is \"" << text << "\".\n";

    return 0;
}
